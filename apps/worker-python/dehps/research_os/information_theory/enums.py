    PRACTICALLY_UNPREDICTABLE = "PRACTICALLY_UNPREDICTABLE"
    INCONCLUSIVE_DUE_TO_POWER = "INCONCLUSIVE_DUE_TO_POWER"
    REPAIR_MEASUREMENT_SYSTEM = "REPAIR_MEASUREMENT_SYSTEM"
