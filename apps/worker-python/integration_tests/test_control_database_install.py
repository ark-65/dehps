def test_installed_roles_require_separate_activation_and_support_real_execution(target, tmp_path):
    spec, admin_dsn, details = target
    installed = installer.install(admin_dsn, spec, ROOT)
    assert installed['status'] == 'INSTALLED_LOGINS_DISABLED'
    clients = {}
    with psycopg.connect(admin_dsn) as admin:
        identities = admin.execute('''SELECT r.rolname,r.rolcanlogin,r.rolpassword,
            r.rolsuper,r.rolcreatedb,r.rolcreaterole,r.rolbypassrls
            FROM pg_authid r WHERE rolname=ANY(%s)''',
            ([installed['owner'], *installed['roles'].values()],)).fetchall()
        assert len(identities) == 4
        assert all(row[1:] == (False,None,False,False,False,False) for row in identities)
        assert admin.execute('SELECT count(*) FROM execution_authority.approvals').fetchone()[0] == 0
        assert admin.execute('SELECT count(*) FROM execution_authority.executions').fetchone()[0] == 0
        # Fixture-only activation. Real Reviewer credentials must be provisioned
        # independently to that authenticated owner, not generated by this agent.
        for kind, role in installed['roles'].items():
            password = uuid4().hex
            admin.execute(sql.SQL('ALTER ROLE {} LOGIN PASSWORD {}').format(sql.Identifier(role), sql.Literal(password)))
            dsn = make_conninfo(**{**details,'dbname':spec['database'],'user':role,'password':password})
            clients[kind] = AuthorityClient(DatabaseBinding(dsn,spec['database'],role))
        outsider = spec['database'] + '_outsider'
        outsider_password = uuid4().hex
        admin.execute(sql.SQL('CREATE ROLE {} LOGIN PASSWORD {}').format(sql.Identifier(outsider),sql.Literal(outsider_password)))
    with pytest.raises(psycopg.Error) as denied:
        psycopg.connect(make_conninfo(**{**details,'dbname':spec['database'],
                                        'user':outsider,'password':outsider_password}))
    # libpq connection-time FATAL errors don't retain SQLSTATE in this psycopg
    # build. Require the actual server CONNECT denial, not any connection error.
    assert f'permission denied for database "{spec["database"]}"' in str(denied.value)
    packet = plan()
    release = 'a'*64
    request = clients['engineer'].request(packet.payload, release)
    content = clients['reviewer'].get(request)['content_sha256']
    with pytest.raises(psycopg.errors.InsufficientPrivilege):
        clients['engineer'].approve(request,content,release,datetime.now(timezone.utc)+timedelta(hours=1))
    with pytest.raises(psycopg.errors.InsufficientPrivilege):
        clients['operator'].approve(request,content,release,datetime.now(timezone.utc)+timedelta(hours=1))
    with pytest.raises(psycopg.errors.InsufficientPrivilege):
        clients['operator'].begin(request,content,release)
    clients['reviewer'].approve(request,content,release,datetime.now(timezone.utc)+timedelta(hours=1))
    with pytest.raises(psycopg.errors.InsufficientPrivilege):
        clients['reviewer'].begin(request,content,release)
    execution = clients['operator'].begin(request,content,release)
    db = clients['operator'].database
    for statement in [
        sql.SQL('SET ROLE {}').format(sql.Identifier(installed['owner'])),
        'CREATE TABLE public.unapproved_write (id integer)',
        'DELETE FROM execution_authority.identities',
        'SELECT * FROM public.research_os_mainline_artifacts',
    ]:
        with pytest.raises(psycopg.errors.InsufficientPrivilege):
            with db.connect() as connection:
                connection.execute(statement)
    tmp_path.chmod(0o700)
    config = {'dsn':db.dsn,'database':db.database,'role':db.role,'root':str(tmp_path),
              'plan':packet.payload,'authorization':{'execution_id':execution,
              'content_sha256':content,'release_sha256':release}}
    first = child(config,'normal')
    assert first.returncode == 0, first.stderr
    before = records(admin_dsn)
    assert before['execution_store.commits'] == before['public.research_os_mainline_artifacts'] == 2
    replay = child(config,'replay')
    assert replay.returncode == 0, replay.stderr
    assert records(admin_dsn) == before
    with pytest.raises(ValueError, match='existing execution schema'):
        installer.install(admin_dsn,spec,ROOT)
    assert records(admin_dsn) == before


@pytest.mark.parametrize('failure',['cluster','principal','sql-bytes','transaction'])
def test_installation_fails_without_partial_roles_or_schema(target,tmp_path,failure):
    spec,admin_dsn,_ = target
    spec = deepcopy(spec)
    source = ROOT
    if failure == 'cluster':
        spec['system_identifier'] = '1'
    elif failure == 'principal':
        spec['principals']['reviewer'] = spec['principals']['engineer']
    elif failure == 'sql-bytes':
        spec['sql_sha256'][installer.SCHEMA_FILES[-1]] = '0'*64
    else:
        source = tmp_path / 'sql-source'
        for name in installer.SCHEMA_FILES:
            path = source/name; path.parent.mkdir(parents=True,exist_ok=True)
            data = (ROOT/name).read_bytes()
            if name == installer.SCHEMA_FILES[-1]: data += b'\nTHIS IS NOT VALID SQL;\n'
            path.write_bytes(data); spec['sql_sha256'][name] = sha256(data).hexdigest()
    with pytest.raises((ValueError,psycopg.errors.SyntaxError)):
        installer.install(admin_dsn,spec,source)
    with psycopg.connect(admin_dsn) as admin:
        assert admin.execute("SELECT count(*) FROM pg_namespace WHERE nspname IN ('execution_authority','execution_store')").fetchone()[0] == 0
        assert admin.execute("SELECT count(*) FROM pg_class WHERE relnamespace='public'::regnamespace").fetchone()[0] == 0
        assert admin.execute('SELECT count(*) FROM pg_roles WHERE rolname LIKE %s',(spec['database']+'_%',)).fetchone()[0] == 0


def test_installation_preserves_an_existing_unrelated_schema(target):
    spec,admin_dsn,_ = target
    with psycopg.connect(admin_dsn) as admin:
        admin.execute('CREATE SCHEMA unrelated')
        admin.execute('CREATE TABLE unrelated.evidence (value text)')
        admin.execute("INSERT INTO unrelated.evidence VALUES ('preserve original')")
    with pytest.raises(ValueError,match='empty control database required'):
        installer.install(admin_dsn,spec,ROOT)
    with psycopg.connect(admin_dsn) as admin:
        assert admin.execute('SELECT value FROM unrelated.evidence').fetchall() == [('preserve original',)]
        assert admin.execute('SELECT count(*) FROM pg_roles WHERE rolname LIKE %s',(spec['database']+'_%',)).fetchone()[0] == 0
