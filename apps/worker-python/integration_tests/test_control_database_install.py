@contextmanager
def control_database_target(details):
    assert details['dbname'] == 'dehps_execution_test_admin'
    database = 'dehps_control_learning_' + uuid4().hex[:8]
    admin_dsn = make_conninfo(**{**details, 'dbname': database})
    roles = [database + '_' + kind for kind in ('engineer', 'reviewer', 'operator', 'owner', 'outsider')]
    with psycopg.connect(make_conninfo(**details), autocommit=True) as admin:
        system_id = admin.execute('SELECT system_identifier::text FROM pg_control_system()').fetchone()[0]
        admin.execute(sql.SQL('CREATE DATABASE {}').format(sql.Identifier(database)))
    spec = {'schema':'dehps-control-database-install.v1', 'database':database,
            'system_identifier':system_id, 'domain':'learning',
            # These isolated test principals are NOT real deployment review.
            'principals':{kind:'installation-test-'+kind for kind in ('engineer','reviewer','operator')},
            'sql_sha256':{name:sha256((ROOT/name).read_bytes()).hexdigest() for name in installer.SCHEMA_FILES}}
    try:
        yield spec, admin_dsn, details
    finally:
        with psycopg.connect(make_conninfo(**details), autocommit=True) as admin:
            admin.execute(sql.SQL('DROP DATABASE {} WITH (FORCE)').format(sql.Identifier(database)))
            for role in roles:
                admin.execute(sql.SQL('DROP ROLE IF EXISTS {}').format(sql.Identifier(role)))


